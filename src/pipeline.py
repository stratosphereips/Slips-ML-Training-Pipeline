# Experiment & Paths
# -------------------------
class ExperimentManager:
    def __init__(self, cfg_reader: ConfigReader):
        self.cfg_reader = cfg_reader
        self.cfg = cfg_reader.load()
        self.classes = cfg_reader.get_classes()
        # deterministic RNG for global usage
        self.rng = np.random.default_rng(int(cfg_reader.get_random_seed()))

        # resolved paths (cfg_reader guarantees experiment_dir_resolved)
        paths = self.cfg_reader.get_paths()
        self.expdir = Path(paths["experiment_dir_resolved"])

        # single output directory (contains logs, models, preprocessing, results)
        self.output_dir = self.expdir / "output"
        self.logs_dir = self.output_dir / "logs"
        self.models_dir = self.output_dir / "models"
        self.preprocessing_dir = self.output_dir / "preprocessing"
        self.results_dir = self.output_dir / "results"

        train_script, test_script = self.cfg_reader.get_plotting_paths()
        self.train_plotting_script = train_script
        self.test_plotting_script = test_script

    def prepare_dirs(self):
        # create main experiment dir and output subdirs
        self.expdir.mkdir(parents=True, exist_ok=True)
        for d in [self.output_dir, self.logs_dir, self.models_dir, self.preprocessing_dir, self.results_dir]:
            d.mkdir(parents=True, exist_ok=True)

        # save effective merged config in experiment root (not in output)
        cfg_path = self.expdir / "config_effective.json"
        with open(cfg_path, "w", encoding="utf-8") as fh:
            json.dump(self.cfg, fh, indent=2)

        # create readme if missing
        readme = self.expdir / "readme.txt"
        if not readme.exists():
            readme.write_text(
                f"Experiment: {self.cfg.get('experiment_name')}\nGenerated by PipelineRunner\n",
                encoding="utf-8",
            )

    def validate_plotting_scripts(self):
        for script in (self.train_plotting_script, self.test_plotting_script):
            if not script or not Path(script).is_file():
                raise FileNotFoundError(f"Plotting script not found: {script}")
        self.train_plotting_script = str(Path(self.train_plotting_script).resolve())
        self.test_plotting_script = str(Path(self.test_plotting_script).resolve())

