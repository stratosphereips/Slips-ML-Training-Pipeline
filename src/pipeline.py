# Single Build Manager (all builders combined)
# -------------------------
class BuildManager:
    """
    Single class to build loaders, feature extractor, preprocessor and classifier.
    Keeps construction logic in one place to reduce bloat.
    """
    def __init__(self, cfg_reader: ConfigReader, exp: ExperimentManager):
        self.cfg_reader = cfg_reader
        self.exp = exp
        self.loaders = None
        self.feature_extractor = None
        self.preprocessor = None
        self.classifier_wrapper = None

    def build_loaders(self):
        ds = self.cfg_reader.get_dataset_loader_params()
        root = self.cfg_reader.load().get("root")
        if not root:
            raise ValueError("Config must define dataset root")
        self.loaders = find_and_load_datasets(
            root_dir=root,
            batch_size=int(ds.get("batch_size", 1000)),
            prefix_regex=ds.get("prefix_regex", r"^\d{3}"),
            data_subdir=ds.get("data_subdir", "data"),
            seed=int(self.cfg_reader.get_random_seed()),
        )
        return self.loaders

    def build_feature_extractor(self):
        params = self.cfg_reader.get_feature_extractor_params()
        self.feature_extractor = FeatureExtraction(**params)
        return self.feature_extractor

    def build_preprocessor(self):
        save_opts = self.cfg_reader.get_preprocessing_save_options()
        prep = PreprocessingWrapper(
            steps=[],
            experiment_name=self.cfg_reader.load().get("experiment_name"),
            base_models_dir=str(self.exp.preprocessing_dir),
            step_filename_template=save_opts.get("step_filename_template", "{name}.bin"),
        )
        for step in self.cfg_reader.get_preprocessing_steps():
            Cls = get_transformer_class(step["type"])
            prep.add_step(step.get("name"), Cls(**(step.get("params") or {})))

        load_from = (self.cfg_reader.load().get("preprocessing") or {}).get("load_from")
        if load_from:
            path = Path(load_from)
            if not path.is_absolute():
                path = self.exp.expdir / path
            prep.load(base_path=str(path))
        self.preprocessor = prep
        return self.preprocessor

    def build_classifier(self):
        spec = self.cfg_reader.get_model_spec()
        cls_type = spec.get("classifier_type") or spec.get("type")
        params = dict(spec.get("classifier_params", {}) or {})

        if "model" in params and isinstance(params["model"], dict):
            params = prepare_river_nested_model_params(params)

        Wrapper = get_wrapper_class(spec.get("wrapper", "SKLearnClassifierWrapper"))

        load_from = spec.get("load_from")
        load_name = spec.get("load_name", spec.get("save_name", "classifier.bin"))

        classifier_obj = None
        if cls_type:
            Cls = get_classifier_class(cls_type)
            try:
                classifier_obj = Cls(**params)
            except Exception:
                classifier_obj = None

        wrapper = Wrapper(
            classifier_obj,
            preprocessing_handler=self.preprocessor,
            classes=self.cfg_reader.get_classes(),
        )

        if load_from:
            path = Path(load_from)
            if not path.is_absolute():
                path = self.exp.expdir / path
            wrapper.load_classifier(str(path), name=load_name)

        self.classifier_wrapper = wrapper
        return self.classifier_wrapper

    def build_all(self):
        # build in sensible order
        loaders = self.build_loaders()
        feat = self.build_feature_extractor()
        prep = self.build_preprocessor()
        clf = self.build_classifier()
        return loaders, feat, prep, clf

