# Command executor
# -------------------------
class CommandExecutor:
    def __init__(self, cfg_reader: ConfigReader, exp: ExperimentManager, loaders, feature_extractor, preprocessor, classifier_wrapper):
        self.cfg_reader = cfg_reader
        self.exp = exp
        self.loaders = loaders
        self.feature_extractor = feature_extractor
        self.preprocessor = preprocessor
        self.classifier_wrapper = classifier_wrapper

    def _ensure_command_paths(self, cmd, idx):
        """
        Ensure each command has paths injected (strings) using output layout.
        All command artifacts will live under the single output directory.
        """
        safe_name = (cmd.get("name") or f"cmd_{idx}").replace(" ", "_")
        cmd_base = self.exp.output_dir / f"{idx}_{safe_name}"
        cmd_base.mkdir(parents=True, exist_ok=True)

        cmd_paths = {
            "command_dir": str(cmd_base.resolve()),
            "logs": str(self.exp.logs_dir.resolve()),
            "model": str(self.exp.models_dir.resolve()),
            "preprocessing": str(self.exp.preprocessing_dir.resolve()),
            "results": str(self.exp.results_dir.resolve()),
        }
        cmd["paths"] = cmd_paths

    def _prepare_mixer_spec(self, cmd):
        """Return a mixer_spec copy with effective validation split injected."""
        mixer_spec = dict(cmd.get("mixer", {}) or {})
        # prefer command-level computed effective validation split
        mixer_spec["validation_split"] = cmd.get(
            "effective_validation_split", mixer_spec.get("validation_split", 0.0)
        )
        # keep effective_batch_size available on command (mixers read effective_batch_size from cmd)
        mixer_spec["effective_batch_size"] = int(cmd.get("effective_batch_size"))
        return mixer_spec

    def _run_train(self, idx, cmd):
        mixer_spec = self._prepare_mixer_spec(cmd)
        mixer = get_mixer_class(mixer_spec["type"])(mixer_spec, self.loaders, self.exp.rng)
        mixer.reset_epoch(int(cmd["effective_batch_size"]), epoch_idx=0)

        logfile = Path(cmd["paths"]["logs"]) / f"{idx}_train.log"
        logger = Logger(logfile_path=str(logfile), overwrite=True)

        while True:
            train_batch, val_batch = mixer.next_batch()
            if train_batch is None and val_batch is None:
                break

            X, y = self.feature_extractor.process_batch(train_batch)
            if X.shape[0] == 0:
                continue

            self.preprocessor.partial_fit(X)
            Xp = self.preprocessor.transform(X)

            self.classifier_wrapper.partial_fit(Xp, np.asarray(y))
            y_pred = self.classifier_wrapper.predict(Xp)

            logger.save_training_results(y_pred, np.asarray(y), None, None, len(y))

        # persist artifacts to output dirs
        self.preprocessor.save(base_path=str(cmd["paths"]["preprocessing"]))
        self.classifier_wrapper.save_classifier(
            path=str(cmd["paths"]["model"]),
            name=self.cfg_reader.get_model_spec().get("save_name", "classifier.bin"),
        )

    def _run_test(self, idx, cmd):
        mixer_spec = self._prepare_mixer_spec(cmd)
        mixer = get_mixer_class(mixer_spec["type"])(mixer_spec, self.loaders, self.exp.rng)
        mixer.reset_epoch(int(cmd["effective_batch_size"]), epoch_idx=0)

        logfile = Path(cmd["paths"]["logs"]) / f"{idx}_test.log"
        logger = Logger(logfile_path=str(logfile), overwrite=True)

        while True:
            batch, _ = mixer.next_batch()
            if batch is None:
                break

            X, y = self.feature_extractor.process_batch(batch)
            if X.shape[0] == 0:
                continue

            Xp = self.preprocessor.transform(X)
            y_pred = self.classifier_wrapper.predict(Xp)

            logger.save_test_results(np.asarray(y), np.asarray(y_pred))

        self.preprocessor.save(base_path=str(cmd["paths"]["preprocessing"]))
        self.classifier_wrapper.save_classifier(
            path=str(cmd["paths"]["model"]),
            name=self.cfg_reader.get_model_spec().get("save_name", "classifier.bin"),
        )


    def _run_command(self, idx, cmd):
        # ensure paths exist
        self._ensure_command_paths(cmd, idx)

        # run the actual command
        if cmd["command"] == "train":
            self._run_train(idx, cmd)
            script = self.exp.train_plotting_script
            log_file = self.exp.logs_dir / f"{idx}_train.log"
        elif cmd["command"] == "test":
            self._run_test(idx, cmd)
            script = self.exp.test_plotting_script
            log_file = self.exp.logs_dir / f"{idx}_test.log"
        else:
            raise ValueError(f"Unknown command '{cmd.get('command')}'")

        plot_evt = f"{idx}_{cmd['command']}"

        # run plotting script pointing directly to the log file
        subprocess.run(
            [
                "python",
                script,
                "-f",
                str(log_file),  # point directly to the log
                "-e",
                plot_evt,
                "--save_folder",
                str(self.exp.results_dir),
            ],
            check=True,
        )



    def run_all(self):
        for idx, cmd in enumerate(self.cfg_reader.get_commands()):
            # ensure effective values are present (ConfigReader should have injected these)
            if "effective_batch_size" not in cmd or "effective_validation_split" not in cmd:
                raise RuntimeError(f"Command {idx} missing effective values: {cmd}")
            self._run_command(idx, cmd)

# -------------------------
# PipelineRunner entry point
# -------------------------
class PipelineRunner:
    def __init__(self, config_path_or_dir):
        self.cfg_reader = ConfigReader(config_path_or_dir)
        # experiment manager handles paths, RNG, scripts, classes
        self.exp = ExperimentManager(self.cfg_reader)
        self.exp.prepare_dirs()
        self.exp.validate_plotting_scripts()

        # single build manager to construct all components
        bm = BuildManager(self.cfg_reader, self.exp)
        self.loaders, self.feature_extractor, self.preprocessor, self.classifier_wrapper = bm.build_all()

    def run(self):
        executor = CommandExecutor(
            self.cfg_reader,
            self.exp,
            self.loaders,
            self.feature_extractor,
            self.preprocessor,
            self.classifier_wrapper,
        )
        executor.run_all()
        return True

# -------------------------
# CLI
# -------------------------
def _cli_main(argv=None):
    argv = argv or sys.argv
    runner = PipelineRunner(argv[1] if len(argv) > 1 else ".")
    runner.run()
    return 0

if __name__ == "__main__":
    sys.exit(_cli_main(sys.argv))
